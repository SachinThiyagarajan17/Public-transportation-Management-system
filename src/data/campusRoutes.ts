// Helper to find all routes stopping at a given stop ID
export function getRoutesForStop(stopId: string): Route[] {
  return CAMPUS_ROUTES.filter((route) =>
    route.stops.some((stop) => stop.id === stopId)
  );
}

// Helper to get all unique stops across all routes
export function getAllUniqueStops(): Stop[] {
  const map = new Map<string, Stop>();
  CAMPUS_ROUTES.forEach((route) => {
    route.stops.forEach((stop) => {
      if (!map.has(stop.id)) {
        map.set(stop.id, stop);
      }
    });
  });
  return Array.from(map.values());
}
